#!/usr/bin/env python3
"""Put the repository back to its showcase starting position.

Run this between demo runs. It does three things, in this order:

  1. `git reset --hard HEAD`  — every tracked file goes back to the last commit,
     so a requirement someone edited live, a link someone broke, and a staged
     experiment are all rolled back.
  2. deletes the Jama-acquired artefacts, so the system-requirement level is
     GONE and `ubc script sync-jama` has something to do.
  3. clears the caches and build output, so the first `ubc check` of the demo is
     a real one rather than an index that was already warm.

Afterwards the tree is exactly where the showcase starts: 20 requirements
missing, every `arch` and `risk` dangling, and one command to fix it.

    ubc script reset       # ask first, then do it
    ubc script reset:dry   # print the plan, change nothing

THIS DISCARDS UNCOMMITTED WORK. Step 1 is `git reset --hard`, so anything not
committed is gone — staged or not. The script prints what it is about to discard
and asks, unless `ALM_RESET_YES=1` says not to (`ubc script` forwards no
arguments of its own, so the environment is the only channel).

What it deliberately does NOT touch:

  * `docs/alm/crosswalk.json` — the ONE file the sync cannot rebuild. It carries
    what Jama does not model: the `traces_to` link up to the user story and the
    stream grouping. Deleting it would break the demo rather than reset it.
  * `.venv/`, `.env`, and anything else ignored but not named below. The cache
    list is an explicit allowlist, not `git clean -fdx`, precisely so a reset
    can never cost someone their environment or their credentials.
  * Jama itself. If the demo edited a requirement in the ALM, that edit is still
    there — a local reset cannot undo it, and the next sync will acquire it.
    Change it back in Jama by hand.
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent

# Generated by `tools/sync_alm.py`. Tracked, so `git reset` brings them back;
# they are deleted afterwards on purpose, to arm the showcase.
ACQUIRED = [
    "docs/specs/_global/alm_requirements.rst",
    "docs/alm/needs.json",
    "docs/alm/external.json",
]

# Never deleted. Named here so the reason travels with the list.
KEEP = {"docs/alm/crosswalk.json": "the sync cannot rebuild it — Jama models no streams"}

# Explicit allowlist. Directories are removed whole, files are unlinked. Globs
# are matched against the repository root, `.venv` excluded everywhere.
CACHES = [
    ".ub_cache",
    "**/.ub_cache",
    "_build",
    "docs/_build",
    "reports/_build",
    "docs/reports/_build",
    ".pytest_cache",
    "**/__pycache__",
    "needs.json",
    "docs/needs.json",
    "docs/needs.lfp.json",
]


def run(*args: str, check: bool = True) -> subprocess.CompletedProcess:
    return subprocess.run(args, cwd=REPO, check=check, capture_output=True, text=True)


def git_status() -> str:
    return run("git", "status", "--short").stdout.rstrip()


def cache_targets() -> list[Path]:
    seen: list[Path] = []
    for pattern in CACHES:
        for path in sorted(REPO.glob(pattern)):
            if ".venv" in path.parts or ".git" in path.parts:
                continue
            if path not in seen:
                seen.append(path)
    return seen


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="print the plan and change nothing",
    )
    parser.add_argument(
        "--yes",
        action="store_true",
        help="skip the confirmation (same as ALM_RESET_YES=1)",
    )
    args = parser.parse_args()

    if not (REPO / ".git").exists():
        print(f"error: {REPO} is not a git repository", file=sys.stderr)
        return 1

    head = run("git", "log", "--oneline", "-1").stdout.strip()
    dirty = git_status()
    caches = cache_targets()
    acquired = [p for p in ACQUIRED if (REPO / p).exists()]

    # `git reset --hard` rewrites TRACKED files only; an untracked file survives
    # it. Saying so is the difference between a warning someone can act on and a
    # warning that over-claims and gets ignored.
    tracked = [l for l in dirty.splitlines() if not l.startswith("??")]
    untracked = [l for l in dirty.splitlines() if l.startswith("??")]

    print(f"reset to: {head}\n")
    if tracked:
        print("WILL BE DISCARDED — uncommitted changes to tracked files:")
        for line in tracked:
            print(f"    {line}")
    else:
        print("no uncommitted changes to tracked files — nothing to lose")
    if untracked:
        print("\nKEPT — untracked, `git reset --hard` does not touch these:")
        for line in untracked:
            print(f"    {line}")
    print()

    print("will delete (re-acquired by `ubc script sync-jama`):")
    for path in acquired or ["    — already gone"]:
        print(f"    {path}" if acquired else path)
    print()

    print("will clear:")
    for path in caches or ["    — nothing cached"]:
        print(f"    {path.relative_to(REPO)}" if caches else path)
    print()

    for path, why in KEEP.items():
        print(f"kept: {path} — {why}")
    print()

    if args.dry_run:
        print("dry run — nothing changed")
        return 0

    if not (args.yes or os.environ.get("ALM_RESET_YES") == "1"):
        if not sys.stdin.isatty():
            print(
                "error: refusing to reset without a terminal to confirm at.\n"
                "       set ALM_RESET_YES=1 if you mean it.",
                file=sys.stderr,
            )
            return 1
        answer = input("type 'reset' to proceed: ").strip()
        if answer != "reset":
            print("aborted — nothing changed")
            return 1

    run("git", "reset", "--hard", "HEAD")
    print(f"rolled back to {head}")

    for rel in ACQUIRED:
        path = REPO / rel
        if path.exists():
            path.unlink()
            print(f"deleted {rel}")

    for path in cache_targets():
        if path.is_dir():
            shutil.rmtree(path, ignore_errors=True)
        else:
            path.unlink(missing_ok=True)
        print(f"cleared {path.relative_to(REPO)}")

    print(
        "\nready. The system-requirement level is gone:\n"
        "    ubc check docs        # every arch and risk now dangles\n"
        "    ubc script sync-jama  # get it back from Jama\n"
        "\nIf the demo edited a requirement IN Jama, that edit is still there —"
        "\nchange it back in the Jama UI; this reset is local only."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
